target("host-tests")
    set_plat("macosx")
    set_arch(os.arch())
    set_toolchains("clang")
    set_kind("binary")
    set_default(false)
    set_targetdir("$(builddir)/host-tests")
    add_files(table.unpack(host_sources))
    add_files(table.unpack(host_tests))
    add_includedirs(table.unpack(host_includes))
    add_mflags("-fobjc-arc", "-Wall", "-Wno-unused-parameter")
    add_mxxflags("-fobjc-arc", "-Wall", "-Wno-unused-parameter")
    add_frameworks("Foundation", "CoreGraphics", "CoreText", "Security", "SystemConfiguration")
    add_syslinks("c++", "crypto", "z")
    add_tests("default")
    on_load(function (target)
        local prefix
        for _, formula in ipairs({"openssl@3", "openssl@1.1", "openssl"}) do
            local found = try { function () return os.iorunv("brew", {"--prefix", formula}):trim() end }
            if not prefix and found and os.isdir(path.join(found, "include", "openssl")) then
                prefix = found
            end
        end
        if not prefix then
            raise("host-tests needs a host OpenSSL for TGCallStun's HMAC-SHA1, and Homebrew has none of openssl@3, openssl@1.1 or openssl")
        end
        target:add("includedirs", path.join(prefix, "include"))
        target:add("linkdirs", path.join(prefix, "lib"))
        local home = path.absolute(path.join(target:targetdir(), "home"))
        os.mkdir(path.join(home, "Library", "Caches"))
        target:add("runenvs", "HOME", home)
    end)
target_end()

target("fuzz-flatten-message")
    set_plat("macosx")
    set_arch(os.arch())
    set_kind("binary")
    set_default(false)
    set_targetdir("$(builddir)/host-tests")
    add_files("../src/Wire/Flatten/TGFlattenMessage.m", "support/tg_flatten_message_fixture.m", "fuzz/tg_flatten_message_fuzz.m")
    add_includedirs("../src/Wire/Flatten", "../src/TDLibClient")
    add_mflags("-fobjc-arc", "-fsanitize=fuzzer,address,undefined", "-Wall", "-Wno-unused-parameter")
    add_ldflags("-fsanitize=fuzzer,address,undefined")
    add_frameworks("Foundation", "CoreGraphics")
    on_load(function (target)
        local llvm = try { function () return os.iorunv("brew", {"--prefix", "llvm"}):trim() end }
        if not llvm or not os.isfile(path.join(llvm, "bin", "clang")) then
            raise("fuzz-flatten-message needs libFuzzer, which Apple's clang lacks: brew install llvm")
        end
        target:set("toolset", "cc", path.join(llvm, "bin", "clang"))
        target:set("toolset", "mm", path.join(llvm, "bin", "clang"))
        target:set("toolset", "ld", path.join(llvm, "bin", "clang"))
    end)
    on_run(function (target)
        os.mkdir(path.join(os.projectdir(), "tests", "fuzz", "corpus", "flatten_message"))
        os.execv(target:targetfile(), table.join({path.join(os.projectdir(), "tests", "fuzz", "corpus", "flatten_message")}, table.wrap(import("core.base.option").get("arguments"))))
    end)
target_end()
