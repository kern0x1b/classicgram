static char TGRunningCaseName[256];
static char TGFatalSignalStack[SIGSTKSZ];

static void TGReportFatalSignal(int signalNumber) {
	const char *label = "\nhost tests: fatal signal while running ";
	write(STDERR_FILENO, label, strlen(label));
	write(STDERR_FILENO, TGRunningCaseName, strlen(TGRunningCaseName));
	write(STDERR_FILENO, "\n", 1);
	void *frames[64];
	int count = backtrace(frames, 64);
	backtrace_symbols_fd(frames, count, STDERR_FILENO);
	_exit(128 + signalNumber);
}

static void TGInstallFatalSignalReporting(void) {
	stack_t alternate;
	memset(&alternate, 0, sizeof(alternate));
	alternate.ss_sp = TGFatalSignalStack;
	alternate.ss_size = sizeof(TGFatalSignalStack);
	sigaltstack(&alternate, NULL);

	struct sigaction action;
	memset(&action, 0, sizeof(action));
	action.sa_handler = TGReportFatalSignal;
	action.sa_flags = SA_ONSTACK;
	sigaction(SIGSEGV, &action, NULL);
	sigaction(SIGBUS, &action, NULL);
	sigaction(SIGILL, &action, NULL);
	sigaction(SIGABRT, &action, NULL);
}
